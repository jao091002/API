CREATE TABLE IF NOT EXISTS produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  quantidade NUMERIC(12, 3) NOT NULL DEFAULT 0,
  valor NUMERIC(12, 2) NOT NULL DEFAULT 0,
  categoria TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS movimentacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tempo TIMESTAMPTZ NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  quantidade NUMERIC(12, 3) NOT NULL,
  id_produto BIGINT NOT NULL REFERENCES produtos(id)
);

CREATE INDEX IF NOT EXISTS idx_movimentacoes_tempo ON movimentacoes(tempo);
CREATE INDEX IF NOT EXISTS idx_movimentacoes_produto ON movimentacoes(id_produto);
